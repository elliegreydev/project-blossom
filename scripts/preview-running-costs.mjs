/**
 * Renders the three running-costs states to a standalone HTML file.
 *
 * Exists because the block is computed after mount, so it never appears in the
 * prerendered HTML and can't be checked by fetching a page. Every string below
 * comes from the real runningCostsStatus(), and the CSS is lifted verbatim
 * from support.module.css and globals.css, so what this shows is the real
 * component rather than a drawing of it.
 *
 *   node --experimental-strip-types scripts/preview-running-costs.mjs
 */
import { writeFileSync } from "node:fs";
import { parseRunningCosts, runningCostsStatus } from "../src/lib/runningCosts.ts";

const out = process.argv[2];
if (!out) throw new Error("Pass an output path.");

// Placeholder figures. The real monthly cost isn't settled yet.
const AUG_14 = new Date(2026, 7, 14, 12);
const AUG_31 = new Date(2026, 7, 31, 12);

const states = [
  {
    caption: "Short. The number is the shortfall, not the total, because that's what someone organising a whip-round needs.",
    status: runningCostsStatus(parseRunningCosts("6000", "2000", "2026-08-14"), AUG_14),
  },
  {
    caption: "Covered. No celebration, no confetti, and still dated.",
    status: runningCostsStatus(parseRunningCosts("6000", "6000", "2026-08-14"), AUG_14),
  },
  {
    caption: "Last day of the month, worded so it never says “0 days left”.",
    status: runningCostsStatus(parseRunningCosts("6000", "5250", "2026-08-31"), AUG_31),
  },
  {
    caption: "No figure set, or figures left over from a previous month. Renders nothing at all, which is what stops the page making a false claim about money.",
    status: runningCostsStatus(parseRunningCosts("6000", "6000", "2026-07-31"), AUG_14),
  },
];

function daysLeftLine(daysLeft, month) {
  if (daysLeft === 0) return `Today is the last day of ${month}.`;
  if (daysLeft === 1) return `One day left in ${month}.`;
  return `${daysLeft} days left in ${month}.`;
}

function card(status) {
  if (!status) return `<div class="nothing">nothing rendered</div>`;
  const headline =
    status.kind === "covered"
      ? `<p class="targetHeadline">${status.month}&rsquo;s costs are covered.</p>`
      : `<p class="targetHeadline">We&rsquo;re ${status.shortfall} short this month.</p>
         <p class="targetDetail">${daysLeftLine(status.daysLeft, status.month)}</p>`;
  return `<section class="target">${headline}<p class="targetAsOf">As of ${status.asOf}.</p></section>`;
}

const html = `<!doctype html>
<meta charset="utf-8">
<title>Running-costs target, all states</title>
<style>
  :root {
    --lavender: #c4b6f6; --plum: #2b1f33;
    --bg: #fcfafc; --bg-raised: #f7f3f8; --border: #ece5ee;
    --text-primary: var(--plum); --text-secondary: #6b5d74; --text-muted: #756a7d;
    --radius-sm: 10px;
    --font-display: Manrope, Inter, -apple-system, "Segoe UI", sans-serif;
  }
  @media (prefers-color-scheme: dark) {
    :root {
      --bg: #1b151f; --bg-raised: #241c29; --border: #342a3a;
      --text-primary: #f1ecf3; --text-secondary: #b8aec0; --text-muted: #a398aa;
    }
  }
  * { margin: 0; padding: 0; box-sizing: border-box; }
  body {
    background: var(--bg); color: var(--text-primary);
    font-family: Inter, -apple-system, "Segoe UI", sans-serif;
    padding: 28px 20px 40px; display: flex; flex-direction: column; gap: 26px;
    max-width: 460px; margin: 0 auto;
  }
  h1 { font-family: var(--font-display); font-size: 19px; }
  .note { font-size: 13px; line-height: 1.6; color: var(--text-secondary); }
  .case { display: flex; flex-direction: column; gap: 9px; }
  .caption { font-size: 12.5px; line-height: 1.55; color: var(--text-muted); }
  .nothing {
    padding: 15px 17px; border: 1px dashed var(--border); border-radius: var(--radius-sm);
    font-size: 13px; color: var(--text-muted); text-align: center; font-style: italic;
  }

  /* Lifted verbatim from support.module.css */
  .target {
    display: flex; flex-direction: column; gap: 5px;
    padding: 15px 17px;
    border: 1px solid var(--border); border-radius: var(--radius-sm);
    background: var(--bg-raised);
  }
  .targetHeadline { font-family: var(--font-display); font-size: 17px; line-height: 1.4; color: var(--text-primary); }
  .targetDetail { font-size: 13.5px; line-height: 1.55; color: var(--text-secondary); }
  .targetAsOf { font-size: 12.5px; line-height: 1.5; color: var(--text-muted); }
</style>
<h1>Running-costs target</h1>
<p class="note">
  Every line below is generated by the real code, not typed out here. The figures are
  placeholders (&pound;60 a month, so the shortfall reads &pound;40) because the actual
  monthly cost isn&rsquo;t settled yet. No progress bar in any state, on purpose.
</p>
${states.map((s) => `<div class="case">${card(s.status)}<p class="caption">${s.caption}</p></div>`).join("\n")}
`;

writeFileSync(out, html, "utf8");
console.log(`Wrote ${out}`);
